-module(emqx_sparkplug_app).

-behaviour(application).

%% `application' API
-export([start/2, stop/1]).

%%------------------------------------------------------------------------------
%% Type declarations
%%------------------------------------------------------------------------------

%%------------------------------------------------------------------------------
%% `application' API
%%------------------------------------------------------------------------------

start(_StartType, _StartArgs) ->
    emqx_sparkplug_hookcb:register_hooks(),
    emqx_sparkplug_sup:start_link().

stop(_State) ->
    emqx_sparkplug_hookcb:unregister_hooks(),
    ok.

