%% @doc The mria table schema of this node, and its comparison with the
%% baseline committed for the current `EMQX_DB_SCHEMA_VSN'.
%%
%% `scripts/test/db-schema-baseline-test.sh' boots a release and calls
%% `check/1' to make sure the baseline matches the tables the code
%% creates. The baseline, together with the transaction BPAPI versions
%% that `scripts/check-db-schema.escript' maintains, is what the
%% version string stands for.
-module(emqx_machine_db_schema).

-export([
    vsn/0,
    tables/0,
    check/0,
    check/1,
    baseline_file/0,
    format_tables/0
]).

-type table_spec() :: {mria:table(), map()}.

%% @doc The declared schema version.
-spec vsn() -> string().
vsn() ->
    emqx_release:db_schema_vsn().

%% @doc The replicated mria tables of this node, in a normalized form
%% that does not depend on the node or on the cluster.
-spec tables() -> [table_spec()].
tables() ->
    lists:sort([
        table_spec(Table, Shard)
     || Shard <- mria_schema:shards(),
        Table <- mria_schema:tables_of_shard(Shard)
    ]).

table_spec(Table, Shard) ->
    {Table, #{
        shard => Shard,
        storage => storage(mnesia:table_info(Table, storage_type)),
        type => mnesia:table_info(Table, type),
        record_name => mnesia:table_info(Table, record_name),
        attributes => mnesia:table_info(Table, attributes),
        index => lists:sort(mnesia:table_info(Table, index))
    }}.

storage({ext, Alias, _Module}) -> Alias;
storage(Storage) -> Storage.

%% @doc Compare the live tables with the baseline shipped in the priv
%% dir of this release.
-spec check() -> ok | {error, map()}.
check() ->
    check(baseline_file()).

%% @doc Compare the live tables with the baseline in the given file.
-spec check(file:filename()) -> ok | {error, map()}.
check(File) ->
    case file:consult(File) of
        {ok, [Baseline]} when is_list(Baseline) ->
            diff(lists:sort(Baseline), tables());
        {ok, Other} ->
            {error, #{reason => bad_baseline, file => File, content => Other}};
        {error, Reason} ->
            {error, #{reason => cannot_read_baseline, file => File, error => Reason}}
    end.

diff(Same, Same) ->
    ok;
diff(Baseline, Live) ->
    {error, #{
        reason => db_schema_baseline_mismatch,
        vsn => vsn(),
        missing_in_live => Baseline -- Live,
        missing_in_baseline => Live -- Baseline
    }}.

-spec baseline_file() -> file:filename().
baseline_file() ->
    filename:join([code:priv_dir(emqx_machine), "db_schema", vsn(), "tables.eterm"]).

%% @doc The live tables as the content of a baseline file.
-spec format_tables() -> iolist().
format_tables() ->
    Entries = [io_lib:format("~p", [Spec]) || Spec <- tables()],
    [
        "%% Replicated mria tables that EMQX creates at boot with the default configuration,\n",
        "%% as of db_schema ",
        vsn(),
        ".\n",
        "%% Generated by scripts/test/db-schema-baseline-test.sh --update. Do not edit.\n",
        "[\n",
        lists:join(",\n", Entries),
        "\n].\n"
    ].
