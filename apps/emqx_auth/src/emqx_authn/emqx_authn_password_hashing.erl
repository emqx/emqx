-spec encode(algorithm_rw()) -> stored_algorithm().
encode(#{name := bcrypt, salt_rounds := SaltRounds}) ->
    #bcrypt{salt_rounds = SaltRounds};
encode(#{name := pbkdf2, mac_fun := MacFun, iterations := Iterations} = Algorithm) ->
    #pbkdf2{
        mac_fun = MacFun,
        iterations = Iterations,
        dk_length = maps:get(dk_length, Algorithm, undefined)
    };
encode(#{name := Name, salt_position := SaltPosition}) ->
    #simple{name = Name, salt_position = SaltPosition}.

-spec decode(stored_algorithm()) -> algorithm_rw().
decode(#bcrypt{salt_rounds = SaltRounds}) ->
    #{name => bcrypt, salt_rounds => SaltRounds};
decode(#pbkdf2{mac_fun = MacFun, iterations = Iterations, dk_length = undefined}) ->
    #{name => pbkdf2, mac_fun => MacFun, iterations => Iterations};
decode(#pbkdf2{mac_fun = MacFun, iterations = Iterations, dk_length = DKLength}) ->
    #{name => pbkdf2, mac_fun => MacFun, iterations => Iterations, dk_length => DKLength};
decode(#simple{name = Name, salt_position = SaltPosition}) ->
    #{name => Name, salt_position => SaltPosition}.

-spec init(algorithm()) -> ok.
init(#{name := bcrypt}) ->
    {ok, _} = application:ensure_all_started(bcrypt),
    ok;
init(#{name := _Other}) ->
    ok.

-spec gen_salt(algorithm_rw()) -> emqx_passwd:salt().
gen_password() ->
    emqx_base62:encode(crypto:strong_rand_bytes(32)).

gen_salt(#{name := plain}) ->
    <<>>;
gen_salt(#{
    name := bcrypt,
    salt_rounds := Rounds
}) ->
    {ok, Salt} = bcrypt:gen_salt(Rounds),
    list_to_binary(Salt);
gen_salt(#{name := Other}) when Other =/= plain, Other =/= bcrypt ->
    <<X:128/big-unsigned-integer>> = crypto:strong_rand_bytes(16),
    iolist_to_binary(io_lib:format("~32.16.0b", [X])).

-spec hash(algorithm_rw(), emqx_passwd:password()) ->
    {emqx_passwd:password_hash(), emqx_passwd:salt()}.
hash(#{name := bcrypt, salt_rounds := _} = Algorithm, Password) ->
    Salt0 = gen_salt(Algorithm),
    Hash = emqx_passwd:hash({bcrypt, Salt0}, Password),
    Salt = Hash,
    {Hash, Salt};
hash(
    #{
        name := pbkdf2,
        mac_fun := MacFun,
        iterations := Iterations
    } = Algorithm,
    Password
) ->
    Salt = gen_salt(Algorithm),
    DKLength = maps:get(dk_length, Algorithm, undefined),
    Hash = emqx_passwd:hash({pbkdf2, MacFun, Salt, Iterations, DKLength}, Password),
    {Hash, Salt};
hash(#{name := Other, salt_position := SaltPosition} = Algorithm, Password) ->
    Salt =
        case SaltPosition of
            disable -> <<>>;
            _ -> gen_salt(Algorithm)
        end,
    Hash = emqx_passwd:hash({Other, Salt, SaltPosition}, Password),
    {Hash, Salt}.

-spec check_password(
    algorithm(),
    emqx_passwd:salt(),
    emqx_passwd:password_hash(),
    emqx_passwd:password()
) -> boolean().
check_password(#{name := bcrypt}, _Salt, PasswordHash, Password) ->
    emqx_passwd:check_pass({bcrypt, PasswordHash}, PasswordHash, Password);
check_password(
    #{
        name := pbkdf2,
        mac_fun := MacFun,
        iterations := Iterations
    } = Algorithm,
    Salt,
    PasswordHash,
    Password
) ->
    DKLength = maps:get(dk_length, Algorithm, undefined),
    emqx_passwd:check_pass({pbkdf2, MacFun, Salt, Iterations, DKLength}, PasswordHash, Password);
check_password(#{name := Other, salt_position := SaltPosition}, Salt, PasswordHash, Password) ->
    emqx_passwd:check_pass({Other, Salt, SaltPosition}, PasswordHash, Password).
